<?php

namespace App\Extensions;

use ReflectionClass;
use ReflectionMethod;
use ReflectionNamedType;
use ReflectionUnionType;
use SilverStripe\Core\Path;
use ReflectionIntersectionType;
use SilverStripe\Core\ClassInfo;
use SilverStripe\Core\Extension;
use SilverStripe\ORM\DataObject;
use SilverStripe\Core\Extensible;
use SilverStripe\ORM\HasManyList;
use SilverStripe\Control\Director;
use SilverStripe\ORM\ManyManyList;
use SilverStripe\Core\Config\Config;
use SilverStripe\Dev\Command\DbBuild;
use SilverStripe\ORM\ManyManyThroughList;
use SilverStripe\PolyExecution\PolyOutput;

/**
 * Dev-only: generates silverstripe-cache/ide-helper.stub on dev/build with ORM relation
 * methods and extension-provided methods so Phpactor resolves them without source annotations.
 *
 * @extends Extension<DbBuild>
 */
class DbBuildIdeHelperExtension extends Extension
{
    private const STUB_PATH = 'silverstripe-cache/ide-helper.stub';

    private static $restart_phpactor_language_server = false;

    /**
     * @var array<string, array<string, string>>
     */
    private array $importCache = [];

    private const RELATION_CONFIG = [
        'has_one',
        'belongs_to',
        'has_many',
        'many_many',
        'belongs_many_many',
    ];

    public function onAfterBuild(PolyOutput $output, bool $populate, bool $testMode): void
    {
        if (!Director::isDev() || $testMode) {
            return;
        }

        $path = Path::join(BASE_PATH, self::STUB_PATH);
        $stub = $this->buildStub();
        $changed = !is_file($path) || file_get_contents($path) !== $stub;

        if ($changed) {
            file_put_contents($path, $stub);

            if (Config::inst()->get(self::class, 'restart_phpactor_language_server') === true) {
                $this->restartPhpactorLanguageServer();
                $output->writeln('<options=bold>' . _t(
                    self::class . '.IdeHelperUpdatedRestarted',
                    'IDE helper updated. Phpactor language server restarted.',
                ) . '</>');
            } else {
                $output->writeln('<options=bold>' . _t(
                    self::class . '.IdeHelperUpdated',
                    'IDE helper updated. Phpactor must reload to use the changes. Set {config}: true to restart it automatically.',
                    ['config' => self::class . '.restart_phpactor_language_server'],
                ) . '</>');
            }
        }

        $output->writeln(['<options=bold>IDE helper written to ' . self::STUB_PATH . '</>', '']);
    }

    private function restartPhpactorLanguageServer(): void
    {
        foreach (glob('/proc/[0-9]*/cmdline') ?: [] as $cmdlineFile) {
            $cmdline = @file_get_contents($cmdlineFile);
            $isPhpactorLsp = $cmdline !== false
                && str_contains($cmdline, 'phpactor')
                && str_contains($cmdline, 'language-server');

            if (!$isPhpactorLsp) {
                continue;
            }

            if (preg_match('#^/proc/(\d+)/cmdline$#', $cmdlineFile, $matches) && function_exists('posix_kill')) {
                @posix_kill((int) $matches[1], 15);
            }
        }
    }

    private function buildStub(): string
    {
        $byNamespace = [];

        foreach ($this->collectTargetClasses() as $class) {
            if (!class_exists($class)) {
                continue;
            }

            $parent = get_parent_class($class);
            $ownRelations = array_diff_key(
                $this->relationMethods($class),
                $parent ? $this->relationMethods($parent) : [],
            );
            $ownExtensionMethods = array_diff_key(
                $this->extensionMethods($class),
                $parent ? $this->extensionMethods($parent) : [],
            );
            $methods = array_replace($ownExtensionMethods, $ownRelations);

            if (!$methods) {
                continue;
            }

            ksort($methods);
            $position = strrpos($class, '\\');
            $namespace = $position === false ? '' : substr($class, 0, $position);
            $shortName = $position === false ? $class : substr($class, $position + 1);
            $byNamespace[$namespace][$shortName] = $methods;
        }

        ksort($byNamespace);
        $stub = "<?php\n\n// Generated by " . self::class . " on dev/build - do not edit.\n";

        foreach ($byNamespace as $namespace => $classes) {
            ksort($classes);
            $stub .= "\nnamespace {$namespace} {\n";

            foreach ($classes as $shortName => $methods) {
                $stub .= "    class {$shortName}\n    {\n";

                foreach ($methods as $methodCode) {
                    $stub .= "{$methodCode}\n\n";
                }

                $stub = rtrim($stub) . "\n    }\n";
            }

            $stub .= "}\n";
        }

        return $stub;
    }

    /**
     * @return list<class-string>
     */
    private function collectTargetClasses(): array
    {
        $classes = [];

        foreach (ClassInfo::subclassesFor(DataObject::class, true) as $class) {
            $classes[$class] = $class;
        }

        foreach (ClassInfo::allClasses() as $class) {
            if (!class_exists($class) || !method_exists($class, 'get_extensions')) {
                continue;
            }

            $uninherited = Config::inst()->get($class, 'extensions', Config::UNINHERITED);

            if (!empty($uninherited)) {
                $classes[$class] = $class;
            }
        }

        return array_values($classes);
    }

    /**
     * @return array<string, string>
     */
    private function relationMethods(string $class): array
    {
        if (!is_subclass_of($class, DataObject::class)) {
            return [];
        }

        $schema = DataObject::getSchema();
        $methods = [];

        foreach (self::RELATION_CONFIG as $key) {
            foreach (array_keys((array) Config::inst()->get($class, $key)) as $name) {
                if (method_exists($class, $name)) {
                    continue;
                }

                switch ($key) {
                    case 'has_one':
                        $target = $schema->hasOneComponent($class, $name);
                        $type = $target ? '\\' . ltrim($target, '\\') : null;

                        break;
                    case 'belongs_to':
                        $target = $schema->belongsToComponent($class, $name);
                        $type = $target ? '\\' . ltrim($target, '\\') : null;

                        break;
                    case 'has_many':
                        $target = $schema->hasManyComponent($class, $name);
                        $type = $target ? '\\' . HasManyList::class . '<\\' . ltrim($target, '\\') . '>' : null;

                        break;
                    default:
                        $component = $schema->manyManyComponent($class, $name);
                        $list = ($component['relationClass'] ?? null) === ManyManyThroughList::class
                            ? ManyManyThroughList::class
                            : ManyManyList::class;
                        $child = $component['childClass'] ?? null;
                        $type = $child ? '\\' . $list . '<\\' . ltrim($child, '\\') . '>' : null;
                }

                if ($type) {
                    $methods[$name] = "        /** @return {$type} */\n        public function {$name}() {}";
                }
            }
        }

        return $methods;
    }

    /**
     * @return array<string, string>
     */
    private function extensionMethods(string $class): array
    {
        if (!in_array(Extensible::class, class_uses($class) ?: [], true) && !method_exists($class, 'get_extensions')) {
            return [];
        }

        $methods = [];
        $baseMethods = get_class_methods(Extension::class);

        foreach ((array) $class::get_extensions() as $extensionClass) {
            if (!is_string($extensionClass) || !class_exists($extensionClass)) {
                continue;
            }

            $rc = new ReflectionClass($extensionClass);

            foreach ($rc->getMethods(ReflectionMethod::IS_PUBLIC) as $rm) {
                $name = $rm->getName();
                $skip = $rm->isStatic()
                    || $rm->isConstructor()
                    || $rm->isDestructor()
                    || str_starts_with($name, '__')
                    || preg_match('/^(update|on)[A-Z]/', $name) === 1
                    || in_array($name, $baseMethods, true)
                    || method_exists($class, $name);

                if ($skip) {
                    continue;
                }

                $methods[$name] = $this->formatReflectionMethod($rm);
            }
        }

        return $methods;
    }

    private function formatReflectionMethod(ReflectionMethod $rm): string
    {
        $params = [];

        foreach ($rm->getParameters() as $param) {
            $piece = '';

            if ($param->hasType()) {
                $typeStr = $this->formatType($param->getType(), $rm->getDeclaringClass()->getName());
                $needsNullable = $param->isOptional()
                    && !$param->isVariadic()
                    && !$param->getType()->allowsNull()
                    && !str_starts_with($typeStr, '?')
                    && !str_contains($typeStr, '|')
                    && !str_contains($typeStr, '&');

                if ($needsNullable) {
                    $typeStr = '?' . $typeStr;
                }

                $piece .= $typeStr . ' ';
            }

            if ($param->isPassedByReference()) {
                $piece .= '&';
            }

            if ($param->isVariadic()) {
                $piece .= '...';
            }

            $piece .= '$' . $param->getName();

            if ($param->isOptional() && !$param->isVariadic()) {
                $piece .= ' = null';
            }

            $params[] = $piece;
        }

        $return = $rm->hasReturnType()
            ? ': ' . $this->formatType($rm->getReturnType(), $rm->getDeclaringClass()->getName())
            : '';
        $doc = $this->extractDocReturn($rm);
        $prefix = $doc ? "        {$doc}\n" : '';
        $signature = $rm->getName() . '(' . implode(', ', $params) . ')' . $return;

        return $prefix . '        public function ' . $signature . ' {}';
    }

    private function formatType(?\ReflectionType $type, string $declaringClass): string
    {
        if ($type instanceof ReflectionNamedType) {
            $name = $type->getName();

            // In the stub, self/static/parent would resolve against the owner instead of the extension.
            $name = match ($name) {
                'self', 'static' => $declaringClass,
                'parent' => get_parent_class($declaringClass) ?: 'mixed',
                default => $name,
            };

            if (!$type->isBuiltin() && $name !== 'mixed') {
                $name = '\\' . ltrim($name, '\\');
            }

            return ($type->allowsNull() && $name !== 'mixed' && $name !== 'null' ? '?' : '') . $name;
        }

        if ($type instanceof ReflectionUnionType) {
            return implode('|', array_map(fn ($t) => $this->formatType($t, $declaringClass), $type->getTypes()));
        }

        if ($type instanceof ReflectionIntersectionType) {
            return implode('&', array_map(fn ($t) => $this->formatType($t, $declaringClass), $type->getTypes()));
        }

        return '';
    }

    private function extractDocReturn(ReflectionMethod $rm): ?string
    {
        $doc = $rm->getDocComment();

        if (!$doc || !preg_match('/@return\s+(\S.*)$/m', $doc, $m)) {
            return null;
        }

        $type = $this->readDocType(preg_replace('#\s*\*/$#', '', $m[1]));

        if ($type === '' || preg_match('/\$this|\b(self|static|parent)\b/', $type)) {
            return null;
        }

        $class = $rm->getDeclaringClass();
        $unresolved = false;
        $resolved = preg_replace_callback(
            '/\\\\?[A-Za-z_][A-Za-z0-9_\\\\-]*/',
            function (array $match) use ($class, &$unresolved): string {
                $name = $match[0];

                // Lowercase identifiers are builtin/pseudo types (string, array, class-string, ...).
                if ($name[0] === '\\' || preg_match('/^[a-z][a-z0-9_-]*$/', $name)) {
                    return $name;
                }

                $fqcn = $this->resolveDocClass($name, $class);

                if ($fqcn === null) {
                    $unresolved = true;

                    return $name;
                }

                return '\\' . $fqcn;
            },
            $type,
        );

        return $unresolved || $resolved === null ? null : "/** @return {$resolved} */";
    }

    /**
     * Reads a PHPDoc type up to the first whitespace outside of <>, {}, () and [].
     */
    private function readDocType(string $text): string
    {
        $depth = 0;
        $length = strlen($text);

        for ($i = 0; $i < $length; $i++) {
            $char = $text[$i];

            if (str_contains('<{([', $char)) {
                $depth++;
            } elseif (str_contains('>})]', $char)) {
                $depth--;
            } elseif ($depth <= 0 && ctype_space($char)) {
                break;
            }
        }

        return substr($text, 0, $i);
    }

    /**
     * @param ReflectionClass<object> $context
     */
    private function resolveDocClass(string $name, ReflectionClass $context): ?string
    {
        $first = strstr($name, '\\', true) ?: $name;
        $rest = substr($name, strlen($first));
        $imports = $this->importsFor($context);

        $candidates = isset($imports[$first])
            ? [$imports[$first] . $rest]
            : array_filter([$context->getNamespaceName() ? $context->getNamespaceName() . '\\' . $name : null, $name]);

        foreach ($candidates as $candidate) {
            if (class_exists($candidate) || interface_exists($candidate)) {
                return ltrim($candidate, '\\');
            }
        }

        return null;
    }

    /**
     * @param ReflectionClass<object> $class
     * @return array<string, string> alias => FQCN from top-level `use` statements
     */
    private function importsFor(ReflectionClass $class): array
    {
        $file = $class->getFileName();

        if (!$file) {
            return [];
        }

        if (!isset($this->importCache[$file])) {
            $imports = [];
            preg_match_all(
                '/^use\s+([^\s;{]+?)(?:\s+as\s+(\w+))?;/m',
                (string) file_get_contents($file),
                $matches,
                PREG_SET_ORDER,
            );

            foreach ($matches as $match) {
                $fqcn = ltrim($match[1], '\\');
                $alias = $match[2] ?? substr(strrchr('\\' . $fqcn, '\\'), 1);
                $imports[$alias] = $fqcn;
            }

            $this->importCache[$file] = $imports;
        }

        return $this->importCache[$file];
    }
}
